#!/usr/bin/env python3
"""Generate build.ninja and the link script from config/functions.us.csv.

    python configure.py && ninja          # build + sha1-verify SLUS_009.35

Each function is one object: src/funcs/<name>.c when it exists, otherwise the
splat asm. Every object's .text and .rodata is pinned to the address it had in
the original executable, so a wrong-sized C function cannot shift its
neighbours. It fails the sha1 (and first_diff.py points at it) or the link
("cannot move location counter backwards").
"""
import argparse
import csv
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "tools"))
from common import (BUILD, CONFIG, EXE_SHA1, GP, VRAM, load_functions,  # noqa: E402
                    unit_path)

HEADER_VRAM = VRAM - 0x800
DATA_GLOBS = ["asm/data/*.s"]
TOOL_DEPS = ["tools/cc.py", "tools/common.py", "toolchain/compiler.toml", "configure.py"]


def rel(p):
    return os.path.relpath(p, ROOT)


def obj_for(src):
    return BUILD / (rel(src) + ".o")


def load_rodata():
    with open(CONFIG / "rodata.us.csv") as f:
        rows = list(csv.DictReader(f))
    for r in rows:
        r["addr"] = int(r["addr"], 16)
    return rows


def plan(funcs, pieces):
    """Return (objects, text_layout, rodata_layout): layouts are (addr, obj) lists."""
    objects = {}  # obj -> (kind, src)
    text, rodata = [], []
    owned_by_c = set()
    for f in funcs:
        c = unit_path(f["name"])
        if c.exists():
            o = obj_for(c)
            objects[o] = ("cc", c)
            owned = f["owned_rodata"].split()
            owned_by_c.update(owned)
            addrs = [p["addr"] for p in pieces if p["name"] in owned]
            if f["rodata_addr"]:
                addrs.append(int(f["rodata_addr"], 16))
            if addrs:
                rodata.append((min(addrs), o))
        else:
            src = ROOT / f["asm"]
            o = obj_for(src)
            objects[o] = ("as", src)
            if f["rodata_addr"]:
                rodata.append((int(f["rodata_addr"], 16), o))
        text.append((f["addr"], o))
    for p in pieces:
        if p["name"] in owned_by_c:
            continue
        src = ROOT / p["asm"]
        o = obj_for(src)
        objects[o] = ("as", src)
        rodata.append((p["addr"], o))
    rodata.sort(key=lambda t: t[0])
    return objects, text, rodata


def link_script(text, rodata, data_objs, header_obj):
    def place(addr, o, sect):
        return f"        . = 0x{addr - VRAM:X}; {rel(o)}({sect})\n"

    out = ["/* generated by configure.py: do not edit */\n",
           "OUTPUT_ARCH(mips)\n",
           "INCLUDE config/link_aliases.us.txt\n",
           "INCLUDE config/undefined_funcs_auto.us.txt\n",
           "INCLUDE config/undefined_syms_auto.us.txt\n",
           f"_gp = 0x{GP:08X};\n",
           "SECTIONS\n{\n",
           f"    .header 0x{HEADER_VRAM:08X} : {{ {rel(header_obj)}(.data) }}\n",
           f"    .main 0x{VRAM:08X} : SUBALIGN(1)\n    {{\n"]
    for addr, o in rodata:
        out.append(place(addr, o, ".rodata .rdata"))
    for addr, o in text:
        out.append(place(addr, o, ".text"))
    for addr, o in data_objs:
        out.append(place(addr, o, ".data .sdata"))
    out.append("    }\n")
    out.append("    /DISCARD/ : { *(.reginfo) *(.MIPS.abiflags) *(.pdr) *(.comment) "
               "*(.gnu.attributes) *(.mdebug*) *(.gptab*) *(.note*) }\n}\n")
    return "".join(out)


def data_objects():
    out = []
    for g in DATA_GLOBS:
        for s in sorted(ROOT.glob(g)):
            first = next(l for l in s.read_text().splitlines() if "/* " in l and "8" in l)
            addr = int(first.split()[2], 16)
            out.append((addr, obj_for(s), s))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.parse_args()
    if not (CONFIG / "functions.us.csv").exists():
        sys.exit("config/functions.us.csv missing: run python tools/split.py")
    funcs = load_functions()
    pieces = load_rodata()
    objects, text, rodata = plan(funcs, pieces)
    data = data_objects()
    header_src = ROOT / "asm/header.s"
    header_obj = obj_for(header_src)
    objects[header_obj] = ("as", header_src)
    for addr, o, s in data:
        objects[o] = ("as", s)

    BUILD.mkdir(parents=True, exist_ok=True)
    ld = BUILD / "link.ld"
    ld.write_text(link_script(text, rodata, [(a, o) for a, o, _ in data], header_obj))

    py = sys.executable
    deps = " ".join(TOOL_DEPS)
    n = [f"# generated by configure.py: do not edit\nninja_required_version = 1.10\n",
         f"builddir = {rel(BUILD)}\n",
         f"rule cc\n  command = {py} tools/cc.py c $in $out --depfile $out.d\n"
         f"  depfile = $out.d\n  deps = gcc\n  description = cc $in\n",
         f"rule as\n  command = {py} tools/cc.py asm $in $out\n  description = as $in\n",
         f"rule ld\n  command = {py} tools/link.py $out\n  description = link $out\n",
         f"rule verify\n  command = {py} tools/link.py --verify $in $out\n"
         f"  description = sha1 $in\n",
         f"rule configure\n  command = {py} configure.py\n  generator = 1\n"
         f"  description = configure\n",
         f"build build.ninja: configure | configure.py config/functions.us.csv "
         f"config/rodata.us.csv\n"]
    for o, (kind, src) in sorted(objects.items()):
        n.append(f"build {rel(o)}: {kind} {rel(src)} | {deps}\n")
    exe = BUILD / "SLUS_009.35"
    n.append(f"build {rel(exe)}: ld | {rel(ld)} tools/link.py "
             + " ".join(rel(o) for o in sorted(objects)) + "\n")
    n.append(f"build {rel(exe)}.ok: verify {rel(exe)}\n")

    # objdiff: one unit per game function (target = original asm, base = the C)
    units, targets = [], []
    for f in funcs:
        if f["segment"] != "game" or f["kind"] != "func":
            continue
        t = BUILD / "target" / f"{f['name']}.o"
        n.append(f"build {rel(t)}: as {f['asm']} | {deps}\n")
        targets.append(rel(t))
        u = {"name": f["name"], "target_path": rel(t),
             "metadata": {"progress_categories": ["game"], "auto_generated": True}}
        c = unit_path(f["name"])
        if c.exists():
            u["base_path"] = rel(obj_for(c))
            u["metadata"]["source_path"] = rel(c)
            u["metadata"]["complete"] = True
        units.append(u)
    n.append("build objdiff: phony " + " ".join(targets) + " "
             + " ".join(rel(o) for o, (k, _) in sorted(objects.items()) if k == "cc") + "\n")
    (ROOT / "objdiff.json").write_text(json.dumps({
        "$schema": "https://raw.githubusercontent.com/encounter/objdiff/main/config.schema.json",
        "custom_make": "ninja", "build_target": False, "build_base": True,
        "watch_patterns": ["*.c", "*.h"],
        "progress_categories": [{"id": "game", "name": "Game"}],
        "units": units}, indent=1) + "\n")
    n.append(f"default {rel(exe)}.ok\n")
    (ROOT / "build.ninja").write_text("".join(n))
    nc = sum(1 for k, _ in objects.values() if k == "cc")
    print(f"configured: {len(text)} functions ({nc} in C), {len(rodata)} rodata placements; "
          f"expect sha1 {EXE_SHA1}")


if __name__ == "__main__":
    main()
