#!/usr/bin/env python3
"""Identify the PsyQ SDK version linked into the executable and name its
library functions.

Matches lab313ru/psx_psyq_signatures (fetched by toolchain/setup.py into
toolchain/dl/) against the exe. For each SDK version it counts the library
objects whose full signature occurs exactly once; the version with the most
matches wins. Ties are reported, not hidden.

    python tools/psyq_identify.py                  # report versions
    python tools/psyq_identify.py --write-syms     # write config/psyq_syms.us.txt
"""
import argparse
import json
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SIGS = ROOT / "toolchain" / "dl" / "psx_psyq_signatures"
EXE = ROOT / "disc" / "files" / "SLUS_009.35"
OUT = ROOT / "config" / "psyq_syms.us.txt"
LOCAL = re.compile(r"^(loc_|text_|data_|bss_|rdata_|sdata_|sbss_|jpt_|def_)")


def pattern(sig):
    parts = []
    for tok in sig.split():
        parts.append(b"." if tok == "??" else re.escape(bytes([int(tok, 16)])))
    return re.compile(b"".join(parts), re.S)


def load_exe(path):
    d = path.read_bytes()
    if d[:8] != b"PS-X EXE":
        sys.exit(f"{path}: not a PS-X EXE")
    t_addr = struct.unpack_from("<I", d, 0x18)[0]
    return d[0x800:], t_addr


def scan(text, version_dir):
    hits = []  # (lib, obj, offset, labels)
    for lib_json in sorted(version_dir.glob("*.json")):
        for obj in json.loads(lib_json.read_text()):
            sig = obj.get("sig", "").strip()
            if len(sig.split()) < 16:  # too short to be meaningful
                continue
            found = [m.start() for m in pattern(sig).finditer(text)]
            if len(found) == 1:
                labels = obj.get("labels", [])
                if isinstance(labels, str):
                    labels = json.loads(labels.replace("'", '"'))
                hits.append((lib_json.name[:-5], obj["name"], found[0], labels))
    return hits


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--exe", default=str(EXE))
    ap.add_argument("--write-syms", action="store_true")
    a = ap.parse_args()
    if not SIGS.exists():
        sys.exit("signatures missing: run python toolchain/setup.py")
    text, base = load_exe(Path(a.exe))

    results = {}
    for vdir in sorted(p for p in SIGS.iterdir() if p.is_dir() and p.name.isdigit()):
        results[vdir.name] = scan(text, vdir)
        print(f"PsyQ {vdir.name:>5}: {len(results[vdir.name]):4d} objects matched")

    best = max(results.values(), key=len)
    top = [v for v, h in results.items() if len(h) == len(best)]
    print(f"best: {', '.join(top)}" + ("  (tie: decide by compiling)" if len(top) > 1 else ""))

    if a.write_syms:
        syms = {}
        for lib, obj, off, labels in best:
            for lab in labels:
                if not LOCAL.match(lab["name"]):
                    syms.setdefault(base + off + lab["offset"], (lab["name"], lib, obj))
        lines = [f"{n} = 0x{addr:08X}; // type:func"
                 for addr, (n, lib, obj) in sorted(syms.items())]
        OUT.write_text(f"// PsyQ {top[0]} library symbols (code labels), generated by tools/psyq_identify.py\n"
                       + "\n".join(lines) + "\n")
        print(f"wrote {OUT.relative_to(ROOT)} ({len(lines)} symbols)")


if __name__ == "__main__":
    main()
